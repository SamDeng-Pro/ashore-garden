    topics = d.get("real_topics", [])
    # 为每个主题匹配范文（按 theme 精确匹配，找不到则按关键词）
    matched = 0
    for t in topics:
        theme = t.get("theme", "")
        se = SAMPLE_ESSAYS.get(theme)
        if not se:
            # 关键词模糊匹配
            for k, v in SAMPLE_ESSAYS.items():
                if k[:6] in theme or theme[:6] in k:
                    se = v
                    break
        if se:
            t["sample_essay"] = se
            matched += 1
    d["real_topics"] = topics
    d["meta"]["updated_at"] = datetime.datetime.now().strftime("%Y-%m-%d")
    with open(ESSAY, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    print(f"已为 {matched}/{len(topics)} 个真题主题补充示范范文+深度剖析")

